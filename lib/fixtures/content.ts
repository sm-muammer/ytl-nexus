const MODIFIED = "2026-11-16T12:00:00.000Z";

let nextId = 1;
function item(
  type: ContentType,
  slug: string,
  title: string,
  audience: ContentItem["audience"],
  body: string,
  extra: Partial<ContentItem> = {},
): ContentItem {
  return {
    id: nextId++,
    type,
    slug,
    title,
    excerpt: body.replace(/<[^>]+>/g, "").slice(0, 140),
    html: body,
    audience,
    businessUnit: null,
    relatedService: null,
    sourceUrl: null,
    order: nextId,
    modified: MODIFIED,
    ...extra,
  };
}

